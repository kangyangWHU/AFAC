# 预编译：term -> 该组其余词
_INDEX: dict[str, list[str]] = {}
for g in SYN_GROUPS:
    for w in g:
        _INDEX[w] = [x for x in g if x != w]

# 按词长降序匹配，避免短词("借款")在长词("保单借款")内重复触发噪声
_TERMS = sorted(_INDEX, key=len, reverse=True)


def expand_query(text: str) -> str:
    """在 query 末尾补上命中的同义词（去重、保序）。原文不变，只追加。"""
    add: list[str] = []
    seen = set()
    for term in _TERMS:
        if term in text:
            for syn in _INDEX[term]:
                if syn not in text and syn not in seen:
                    add.append(syn); seen.add(syn)
    return text + " " + " ".join(add) if add else text
